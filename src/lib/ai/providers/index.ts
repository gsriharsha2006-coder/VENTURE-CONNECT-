type Recommendation = NonNullable<VcReportContent["finalRecommendation"]>;

function scoreFromInput(input: ReportGenerationInput): number {
  const filled = Object.values(input.sections).filter((value) => value.trim().length > 0).length;
  const completionScore = Math.round(input.completionPercentage * 0.45);
  return Math.max(40, Math.min(92, 38 + completionScore + filled));
}

function recommendation(score: number): Recommendation {
  if (score >= 88) return "Strong Candidate";
  if (score >= 78) return "Investor Conversation Ready";
  if (score >= 68) return "Incubator Ready";
  if (score >= 55) return "Needs Validation";
  return "Not Ready";
}

function evidence(input: ReportGenerationInput, keys: string[], missing: string): string {
  for (const key of keys) {
    const value = input.sections[key]?.trim();
    if (value) return value.slice(0, 900);
  }
  return missing;
}


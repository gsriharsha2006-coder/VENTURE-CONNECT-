export class GeminiProvider implements AIProvider {
  readonly name = "gemini" as const;
  readonly model: string;
  private readonly ai: GoogleGenAI;

  constructor() {
    const apiKey = process.env.GEMINI_API_KEY?.trim();
    if (!apiKey) throw new AIProviderError("NOT_CONFIGURED", "Gemini is not configured on the server.");
    this.model = process.env.GEMINI_MODEL?.trim() || DEFAULT_GEMINI_MODEL;
    this.ai = new GoogleGenAI({ apiKey });
  }

  async generateReport(input: ReportGenerationInput) {
    try {
      const response = await this.ai.models.generateContent({
        model: this.model,
        contents: buildReportPrompt(input),
        config: {
          systemInstruction: REPORT_SYSTEM_INSTRUCTION,
          temperature: 0.2,
          maxOutputTokens: 8192,
          responseMimeType: "application/json",
          responseJsonSchema: buildReportJsonSchema(input.reportType),
          httpOptions: { timeout: GEMINI_TIMEOUT_MS }
        }
      });

      const text = response.text?.trim();
      if (!text) throw new AIProviderError("REFUSAL", "Gemini did not return report content.");
      const payload = parseStructuredReportOutput(text, input.reportType);
      return toVcReportContent(payload);
    } catch (error) {
      if (error instanceof AIProviderError) throw error;
      if (error instanceof ReportValidationError) {
        throw new AIProviderError("INVALID_OUTPUT", "Gemini returned an invalid structured report.");
      }

      const details = error instanceof Error ? error.message.toLowerCase() : "";
      if (details.includes("timeout") || details.includes("timed out") || details.includes("abort")) {
        throw new AIProviderError("TIMEOUT", "Gemini report generation timed out.");
      }
      if (details.includes("429") || details.includes("quota") || details.includes("resource_exhausted")) {
        throw new AIProviderError("QUOTA", "Gemini report generation is temporarily rate limited.");
      }
      throw new AIProviderError("PROVIDER_ERROR", "Gemini report generation failed.");
    }
  }
}
